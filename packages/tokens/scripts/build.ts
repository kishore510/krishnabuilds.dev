// Checks WCAG AA contrast, then writes dist/tokens.css.
// Run with `node scripts/build.ts` (Node strips the types).

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  primitives,
  semantic,
  type SemanticColor,
  type Theme,
} from "../src/tokens.ts";

const PREFIX = "kb";
const AA_TEXT = 4.5;
const THEMES: Theme[] = ["light", "dark"];

// [foreground, background]
const CONTRAST_PAIRS: [SemanticColor, SemanticColor][] = [
  ["text", "bg"],
  ["text", "surface"],
  ["text-muted", "bg"],
  ["text-muted", "surface"],
  ["danger", "bg"],
  ["danger", "surface"],
  ["accent-fg", "accent"],
];

// --- Contrast ---

function luminance(hex: string): number {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

function resolve(token: SemanticColor, theme: Theme): string {
  return primitives.color[semantic.color[token][theme]];
}

let failed = false;
console.log("Contrast (WCAG AA text, min 4.5:1)");
for (const theme of THEMES) {
  for (const [fg, bg] of CONTRAST_PAIRS) {
    const ratio = contrast(resolve(fg, theme), resolve(bg, theme));
    const pass = ratio >= AA_TEXT;
    if (!pass) failed = true;
    console.log(
      `  ${pass ? "PASS" : "FAIL"}  ${theme.padEnd(5)}  ${`${fg} on ${bg}`.padEnd(26)} ${ratio.toFixed(2)}:1`,
    );
  }
}
if (failed) {
  console.error("Contrast check failed; dist/tokens.css not written.");
  process.exit(1);
}

// --- CSS ---

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function flatten(obj: object, path: string[] = []): string[] {
  return Object.entries(obj).flatMap(([key, value]) =>
    typeof value === "object"
      ? flatten(value, [...path, kebab(key)])
      : [`  --${PREFIX}-${[...path, kebab(key)].join("-")}: ${value};`],
  );
}

function semanticVars(theme: Theme, indent = "  "): string[] {
  return [
    `${indent}color-scheme: ${theme};`,
    ...Object.entries(semantic.color).map(
      ([name, values]) =>
        `${indent}--${PREFIX}-color-${name}: var(--${PREFIX}-color-${values[theme]});`,
    ),
  ];
}

const css = [
  "/* Generated by scripts/build.ts. Do not edit. */",
  "",
  ":root {",
  ...flatten(primitives),
  ...semanticVars("light"),
  "}",
  "",
  "@media (prefers-color-scheme: dark) {",
  '  :root:not([data-theme="light"]) {',
  ...semanticVars("dark", "    "),
  "  }",
  "}",
  "",
  ':root[data-theme="dark"] {',
  ...semanticVars("dark"),
  "}",
  "",
  ':root[data-theme="light"] {',
  ...semanticVars("light"),
  "}",
  "",
].join("\n");

const outDir = join(import.meta.dirname, "..", "dist");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "tokens.css"), css);
console.log("Wrote dist/tokens.css");
